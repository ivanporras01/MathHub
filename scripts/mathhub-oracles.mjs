const N=s=>(s||'').replaceAll('−','-').replace(/-\s+(?=\d)/g,'-').match(/-?\d+(?:\.\d+)?/g)?.map(Number)||[];
const gcd=(a,b)=>b?gcd(b,a%b):a;
export function extraOracle(id,q){const p=N(q.prompt),e=N(q.expression);switch(id){
case '6-factors':return q.prompt.includes('greatest')?gcd(...p):p[0]*p[1]/gcd(...p);
case '6-fraction-product':return e[0]/e[1]*e[2]/e[3];
case '6-coordinate':return p[0]>0?(p[1]>0?1:4):(p[1]>0?2:3);
case '6-conversions':return p[0]*(q.prompt.includes('hours')?60:q.prompt.includes('centimeters to meters')?.01:100);
case '7-scale':return p[1]*p[2];
case '7-inequalities':case '8-inequalities':{const boundary=(e[2]-e[1])/e[0];return e[0]<0?boundary-1:boundary+1;}
case '7-compound':return (p[0]/(p[0]+p[1]))**2;
case '7-solids':return q.prompt.includes('surface')?2*(p[0]*p[1]+p[0]*p[2]+p[1]*p[2]):p[0]*p[1]*p[2];
case '8-evaluate':return e[0]*p[0]**2+e[2]*p[0]+e[3];
case '8-distribute':return e[0]+e[2];
case '8-percent':return p[1]*100/p[0];
case '9-expressions':return expressionOracle(q);
case '9-equations':return (e[3]-e[2])/e[0]-e[1];
case '9-inequalities':return (e[2]-e[1])/e[0];
case '9-functions':return p[0]*p[2]**2+p[1];
case '9-slope':return (p[3]-p[1])/(p[2]-p[0]);
case '9-lines':return p[0]*p[2]+p[1];
case '9-systems':return (e[2]-e[1])/(e[0]-1);
case '9-exponents':return Math.sqrt(e[0])+e[1]**e[2];
case '9-polynomials':return e[0]+e[1];
case '9-factoring':return (p[0]-Math.sqrt(p[0]**2-4*p[1]))/2;
case '9-quadratics':return (-e[0]+Math.sqrt(e[0]**2-4*e[1]))/2;
case '9-exponential':return p[0]*(q.prompt.includes('halves')?.5:2)**p[1];
case '10-transformations':return -e[0];
case '10-composition':return p[0]*(p[3]**2+p[2])+p[1];
case '10-inverses':return (p[2]-p[1])/p[0];
case '10-completing-square':return p[1]-(p[0]/2)**2;
case '10-complex':return e[0]*e[2]-e[1]*e[3];
case '10-division':return p[0]-p[2];
case '10-zeros':return Math.max(...e.map(x=>-x));
case '10-rational':return -e[1];
case '10-radicals':return e[1]**2-e[0];
case '10-exponential':return Math.round(Math.log(e[2])/Math.log(e[0]))-e[1];
case '10-logarithms':return Math.round(Math.log(p[1])/Math.log(p[0]));
case '10-nonlinear-systems':return (e[0]+Math.sqrt(e[0]**2+4*e[1]))/2;
case '11-coordinates':return q.prompt.includes('distance')?Math.hypot(p[2]-p[0],p[3]-p[1]):(p[0]+p[2])/2;
case '11-angles':return (q.prompt.includes('complementary')?90:180)-p[0];
case '11-parallel':return q.prompt.includes('same-side')?180-p[0]:p[0];
case '11-triangle-angles':return 180-p[0]-p[1];
case '11-congruence':return p[0];
case '11-transformations':return q.prompt.includes('Translate')?p[1]+p[3]:q.prompt.includes('new x')?-p[0]:-p[1];
case '11-similarity':return p[0]*p[1];
case '11-pythagorean':return q.prompt.includes('one leg')?Math.sqrt(p[0]**2-p[1]**2):Math.hypot(...p);
case '11-trigonometry':return q.prompt.includes('sin(')?p[0]/p[2]:q.prompt.includes('cos(')?p[1]/p[2]:p[0]/p[1];
case '11-quadrilaterals':return q.prompt.includes('opposite')?p[0]:180-p[0];
case '11-circles':return Math.sqrt(e[2]);
case '11-measurement':return p[0]**2*p[1]/(q.prompt.includes('cone')?3:1);
default:throw Error('Missing independent oracle: '+id);
}}
